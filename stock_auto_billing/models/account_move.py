# -*- coding: utf-8 -*-
"""Order-confirmation metadata and credit-note-driven stock returns."""

import logging
from collections import defaultdict

from odoo import _, fields, models
from odoo.exceptions import UserError

_logger = logging.getLogger(__name__)


class AccountMove(models.Model):
    _inherit = 'account.move'

    sab_order_confirmation = fields.Boolean(
        string='Created on Order Confirmation',
        copy=False,
        readonly=True,
        help='Technical marker for invoices and bills created when an order was confirmed.',
    )
    sab_created_from_stock_return = fields.Boolean(
        string='Created from Stock Return',
        copy=False,
        readonly=True,
        help='Prevents a credit note generated by a validated return from creating '
             'a second stock return when it is posted.',
    )

    def action_post(self):
        result = super().action_post()
        credit_notes = self.filtered(
            lambda move: move.state == 'posted'
            and move.move_type in ('out_refund', 'in_refund')
        )
        for credit_note in credit_notes:
            try:
                with self.env.cr.savepoint():
                    credit_note.sudo()._sab_create_returns_from_credit_note()
            except Exception as error:
                _logger.exception(
                    'Could not create stock returns for credit note %s',
                    credit_note.display_name,
                )
                credit_note.sudo().message_post(body=_(
                    'Automatic stock return was not completed for this credit note: %s',
                    error,
                ))
        return result

    def _sab_create_returns_from_credit_note(self):
        """Create exact-quantity stock returns when a linked credit note is posted."""
        self.ensure_one()
        if self.sab_created_from_stock_return or not self.reversed_entry_id:
            return

        is_customer_return = self.move_type == 'out_refund'
        setting = (
            'sab_auto_validate_customer_return_on_credit_note'
            if is_customer_return
            else 'sab_auto_validate_vendor_return_on_credit_note'
        )
        if not getattr(self.company_id, setting):
            return

        picking_model = self.env['stock.picking'].sudo().with_company(self.company_id)
        existing_returns = picking_model.search([
            ('sab_credit_note_id', '=', self.id),
            ('state', '!=', 'cancel'),
        ], limit=1)
        if existing_returns:
            return

        # A credit note only drives stock when its product lines retain a direct
        # link to a sale or purchase order line from the reversed document.
        quantities_by_order_line = defaultdict(float)
        matched_stock_lines = 0
        for credit_line in self.invoice_line_ids.filtered(
            lambda line: line.product_id
            and line.display_type in (False, 'product')
            and line.product_id.type != 'service'
        ):
            if is_customer_return:
                order_lines = credit_line.sale_line_ids
                order_line_uom = lambda line: line.product_uom_id
            else:
                order_lines = credit_line.purchase_line_id
                order_line_uom = lambda line: line.uom_id

            if len(order_lines) != 1:
                raise UserError(_(
                    'Credit note line for %s is not linked to exactly one sales or '
                    'purchase order line; no automatic stock return was created.',
                    credit_line.product_id.display_name,
                ))
            order_line = order_lines[0]
            matched_stock_lines += 1
            source_uom = credit_line.product_uom_id or credit_line.product_id.uom_id
            target_uom = order_line_uom(order_line)
            quantity = source_uom._compute_quantity(
                abs(credit_line.quantity), target_uom, round=False
            )
            if target_uom.is_zero(quantity):
                continue
            quantities_by_order_line[order_line] += quantity

        if not matched_stock_lines or not quantities_by_order_line:
            self.message_post(body=_(
                'Automatic stock return was skipped because no linked stockable '
                'sales or purchase lines were found on the credit note.'
            ))
            return

        expected_code = 'outgoing' if is_customer_return else 'incoming'
        allocations_by_source_move = defaultdict(float)
        for order_line, requested_quantity in quantities_by_order_line.items():
            source_moves = order_line.move_ids.filtered(
                lambda move: move.state == 'done'
                and not move.origin_returned_move_id
                and move.picking_id.state == 'done'
                and move.picking_id.picking_type_code == expected_code
            ).sorted(lambda move: (move.date, move.id))
            if not source_moves:
                raise UserError(_(
                    'No completed source stock operation was found for %s.',
                    order_line.product_id.display_name,
                ))
            if any(move.product_id.tracking for move in source_moves):
                raise UserError(_(
                    'Automatic return for tracked product %s requires a manual '
                    'lot/serial selection.', order_line.product_id.display_name
                ))

            remaining = requested_quantity
            order_uom = (
                order_line.product_uom_id if is_customer_return else order_line.uom_id
            )
            for source_move in source_moves:
                move_uom = source_move.uom_id
                original_quantity = move_uom._compute_quantity(
                    source_move.quantity, order_uom, round=False
                )
                returned_quantity = sum(
                    return_move.uom_id._compute_quantity(
                        return_move.quantity, order_uom, round=False
                    )
                    for return_move in source_move.returned_move_ids
                    if return_move.state == 'done'
                )
                available = max(0.0, original_quantity - returned_quantity)
                take = min(remaining, available)
                if order_uom.is_zero(take):
                    continue
                allocations_by_source_move[source_move] += order_uom._compute_quantity(
                    take, move_uom, round=False
                )
                remaining -= take
                if order_uom.is_zero(remaining):
                    break

            if not order_uom.is_zero(remaining):
                raise UserError(_(
                    'Credit note quantity for %s exceeds the quantity available '
                    'to return from completed stock operations.',
                    order_line.product_id.display_name,
                ))

        allocations_by_picking = defaultdict(dict)
        for source_move, quantity in allocations_by_source_move.items():
            allocations_by_picking[source_move.picking_id][source_move] = quantity

        created_returns = picking_model.browse()
        for source_picking, allocations in allocations_by_picking.items():
            return_picking = source_picking._create_return()
            return_moves = return_picking.move_ids
            for return_move in return_moves:
                source_move = return_move.origin_returned_move_id
                quantity = allocations.get(source_move)
                if not quantity:
                    return_move.unlink()
                    continue
                return_move.product_uom_qty = quantity

            return_picking.write({
                'sab_credit_note_id': self.id,
                'origin': _('%(origin)s / %(credit_note)s',
                            origin=return_picking.origin or source_picking.name,
                            credit_note=self.name),
            })
            return_picking.action_confirm()
            return_picking.action_assign()
            active_moves = return_picking.move_ids.filtered(
                lambda move: move.state not in ('done', 'cancel')
            )
            for move in active_moves:
                source_move = move.origin_returned_move_id
                move.quantity = allocations[source_move]

            if (
                return_picking.picking_type_code == 'outgoing'
                and any(move.state != 'assigned' for move in active_moves)
            ):
                raise UserError(_(
                    'Automatic vendor return was skipped because the returned '
                    'quantity could not be fully reserved for %s.',
                    return_picking.name,
                ))

            result = return_picking.with_context(
                skip_backorder=True,
                skip_zero_demand_check=True,
            ).button_validate()
            if isinstance(result, dict) or return_picking.state != 'done':
                raise UserError(_(
                    'Odoo requires a manual stock operation to complete return %s.',
                    return_picking.name,
                ))
            created_returns |= return_picking

        if created_returns:
            self.message_post(body=_(
                'Stock return(s) %(pickings)s were validated from the quantities '
                'on this posted credit note.',
                pickings=', '.join(created_returns.mapped('name')),
            ))
